'use client';

import React, { useState } from 'react';
import { X, KeyRound, ArrowRight, Loader2, CheckCircle2 } from 'lucide-react';
import { World } from '@/types';

interface JoinWorldModalProps {
  isOpen: boolean;
  onClose: () => void;
  onJoin: (inviteCode: string) => Promise<World>;
  initialCode?: string;
}

export default function JoinWorldModal({
  isOpen,
  onClose,
  onJoin,
  initialCode = '',
}: JoinWorldModalProps) {
  const [code, setCode] = useState(initialCode);
  const [isJoining, setIsJoining] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [successMessage, setSuccessMessage] = useState<string | null>(null);

  if (!isOpen) return null;

  const handleSubmit = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!code.trim()) {
      setError('Please enter a valid invite code');
      return;
    }

    setIsJoining(true);
    setError(null);

    try {
      const world = await onJoin(code.trim().toUpperCase());
      setSuccessMessage(`Successfully joined ${world.name}!`);
      setTimeout(() => {
        setSuccessMessage(null);
        setCode('');
        onClose();
      }, 1200);
    } catch (err: any) {
      setError(err.message || 'Failed to join world. Verify the code.');
    } finally {
      setIsJoining(false);
    }
  };

  return (
    <div className="modal-overlay" onClick={onClose}>
      <div
        className="glass-panel modal-content"
        onClick={(e) => e.stopPropagation()}
        style={{ padding: 24, maxWidth: 460 }}
      >
        <div style={{ display: 'flex', alignItems: 'center', justifyContent: 'space-between', marginBottom: 20 }}>
          <div style={{ display: 'flex', alignItems: 'center', gap: 10 }}>
            <div
              style={{
                width: 38,
                height: 38,
                borderRadius: 'var(--radius-md)',
                background: 'rgba(16, 185, 129, 0.15)',
                color: 'var(--accent-emerald)',
                display: 'flex',
                alignItems: 'center',
                justifyContent: 'center',
              }}
            >
              <KeyRound size={20} />
            </div>
            <div>
              <h3 style={{ fontSize: '1.125rem', fontWeight: 700, color: '#ffffff' }}>Join a World</h3>
              <p style={{ fontSize: '0.75rem', color: 'var(--text-muted)' }}>
                Enter an invite code provided by a world creator
              </p>
            </div>
          </div>
          <button onClick={onClose} className="btn-icon" style={{ border: 'none' }}>
            <X size={18} />
          </button>
        </div>

        {error && (
          <div
            style={{
              padding: '10px 14px',
              borderRadius: 'var(--radius-md)',
              background: 'rgba(244, 63, 94, 0.15)',
              border: '1px solid rgba(244, 63, 94, 0.3)',
              color: '#fda4af',
              fontSize: '0.8125rem',
              marginBottom: 16,
            }}
          >
            {error}
          </div>
        )}

        {successMessage && (
          <div
            style={{
              padding: '10px 14px',
              borderRadius: 'var(--radius-md)',
              background: 'rgba(16, 185, 129, 0.15)',
              border: '1px solid rgba(16, 185, 129, 0.3)',
              color: '#6ee7b7',
              fontSize: '0.8125rem',
              display: 'flex',
              alignItems: 'center',
              gap: 8,
              marginBottom: 16,
            }}
          >
            <CheckCircle2 size={16} />
            <span>{successMessage}</span>
          </div>
        )}

        <form onSubmit={handleSubmit} style={{ display: 'flex', flexDirection: 'column', gap: 16 }}>
          <div>
            <label style={{ display: 'block', fontSize: '0.8125rem', fontWeight: 600, color: 'var(--text-secondary)', marginBottom: 6 }}>
              World Invite Code
            </label>
            <input
              type="text"
              className="input-field"
              placeholder="e.g. TERRA-777 or MW-9X4A72"
              value={code}
              onChange={(e) => setCode(e.target.value.toUpperCase())}
              style={{
                fontFamily: "'JetBrains Mono', monospace",
                fontSize: '1.1rem',
                letterSpacing: '0.1em',
                textAlign: 'center',
                textTransform: 'uppercase',
                padding: '12px 14px',
              }}
              required
              autoFocus
            />
            <p style={{ fontSize: '0.75rem', color: 'var(--text-muted)', marginTop: 6 }}>
              Invite codes are unique keys generated by the world owner.
            </p>
          </div>

          <div style={{ display: 'flex', justifyContent: 'flex-end', gap: 10, marginTop: 10 }}>
            <button
              type="button"
              onClick={onClose}
              className="btn btn-secondary"
              disabled={isJoining}
            >
              Cancel
            </button>
            <button
              type="submit"
              className="btn btn-emerald"
              disabled={isJoining || !code.trim()}
              style={{ minWidth: 130 }}
            >
              {isJoining ? (
                <>
                  <Loader2 size={16} className="animate-spin" />
                  <span>Joining...</span>
                </>
              ) : (
                <>
                  <span>Join World</span>
                  <ArrowRight size={16} />
                </>
              )}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
